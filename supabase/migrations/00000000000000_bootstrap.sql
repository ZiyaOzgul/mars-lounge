-- 8. REALTIME PUBLICATION ÜYELİĞİ
-- =============================================================================
-- Her tabloyu supabase_realtime publication'ına, zaten üye değilse ekler.

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'categories', 'ingredients', 'order_items', 'orders',
    'payment_items', 'payments', 'product_variants', 'products', 'tables'
  ]
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_publication_tables
      WHERE pubname = 'supabase_realtime'
        AND schemaname = 'public'
        AND tablename = t
    ) THEN
      EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', t);
    END IF;
  END LOOP;
END $$;


