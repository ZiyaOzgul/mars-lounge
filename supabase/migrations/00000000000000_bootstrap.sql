CREATE OR REPLACE FUNCTION public.normalize_phone(p text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
AS $function$
  SELECT NULLIF(
    CASE
      WHEN length(d) > 10 AND left(d, 2) = '90' THEN right(d, 10)
      WHEN length(d) = 11 AND left(d, 1) = '0'  THEN right(d, 10)
      ELSE d
    END, '')
  FROM (SELECT regexp_replace(coalesce(p, ''), '[^0-9]', '', 'g') AS d) t
$function$;

-- normalize_phone() artık mevcut — telefon bazlı benzersiz index'i şimdi kurabiliriz.
CREATE UNIQUE INDEX IF NOT EXISTS profiles_customer_phone_unique
  ON public.profiles USING btree (normalize_phone(phone))
  WHERE ((role = 'customer'::text) AND (phone IS NOT NULL) AND (phone <> ''::text));

CREATE OR REPLACE FUNCTION public.is_staff()
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role in ('admin', 'waiter')
  );
$function$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  INSERT INTO public.profiles (id, full_name, phone, role, loyalty_points)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'full_name', ''),
    public.normalize_phone(NEW.raw_user_meta_data->>'phone'),
    COALESCE(NEW.raw_user_meta_data->>'role', 'customer'),
    0
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.phone_in_use(p_phone text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT EXISTS (
    SELECT 1 FROM profiles
    WHERE role = 'customer'
      AND normalize_phone(phone) IS NOT NULL
      AND normalize_phone(phone) = normalize_phone(p_phone)
  );
$function$;

CREATE OR REPLACE FUNCTION public.award_loyalty_points()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  earned integer;
begin
  if new.status = 'completed'
     and (old.status is distinct from 'completed')
     and new.user_id is not null then

    select coalesce(sum(oi.quantity * p.points_value), 0)
      into earned
      from order_items oi
      join products p on p.id = oi.product_id
      where oi.order_id = new.id;

    if earned > 0 then
      update profiles
        set loyalty_points = coalesce(loyalty_points, 0) + earned
        where id = new.user_id;
    end if;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.revoke_loyalty_points()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  earned integer;
begin
  if new.status = 'cancelled'
     and old.status = 'completed'
     and new.user_id is not null then

    select coalesce(sum(oi.quantity * p.points_value), 0)
      into earned
      from order_items oi
      join products p on p.id = oi.product_id
      where oi.order_id = new.id;

    if earned > 0 then
      update profiles
        set loyalty_points = greatest(0, coalesce(loyalty_points, 0) - earned)
        where id = new.user_id;
    end if;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.redeem_loyalty_points(p_user_id uuid, p_points integer, p_expected_balance integer)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_new_balance integer;
begin
  if not is_staff() then
    raise exception 'yetkisiz: sadece personel puan kullanabilir';
  end if;
  if p_points is null or p_points <= 0 then
    raise exception 'geçersiz puan miktarı';
  end if;

  -- Optimistic lock: only deduct if the balance still equals what the
  -- cashier saw on screen — a concurrent spend elsewhere matches 0 rows.
  update profiles
     set loyalty_points = loyalty_points - p_points
   where id = p_user_id
     and loyalty_points = p_expected_balance
     and loyalty_points >= p_points
  returning loyalty_points into v_new_balance;

  if v_new_balance is null then
    raise exception 'bakiye değişti';
  end if;
  return v_new_balance;
end;
$function$;


